"""Recover authored water rows from the local, unmodified Skate 2 data.

Input XEX image is produced by rexglue dump-xex (base 0x82000000).
Offsets are for this integration's original Skate 2 executable/database.
No game archive is modified. See reports/skate2_water_materials.md.
"""
import argparse
import hashlib
import json
import math
import struct
from pathlib import Path


def extract(image, database):
    def floats(address, count):
        return struct.unpack_from('>' + 'f' * count, image, address - 0x82000000)
    period, = floats(0x822CCFFC, 1)
    scale, = floats(0x821082B0, 1)
    assert abs(period - 1 / 30) < 1e-8 and abs(scale - 1 / 255) < 1e-9
    # Constructor 82660738: 30 frames, 3 channels, 8 coefficients/channel.
    # Update 823B51A8: frame modulo 30, no interpolation on this table path;
    # mean and coefficients are normalized by the executable's 1/255 float.
    frames = []
    for frame in range(30):
        mean = floats(0x82D65BB0 + frame * 12, 3)
        weights = floats(0x82D65D18 + frame * 96, 24)
        assert all(math.isfinite(x) for x in (*mean, *weights))
        assert all(120 < x < 255 for x in mean)
        frames.append([x * scale for x in mean] + [0.] + [x * scale for x in weights])
    params = {}
    for name, offset in [('flowing', 0x982D0), ('default', 0x98390)]:
        params[name] = [list(struct.unpack_from('>4f', database, offset + 16 + i * 16))
                        for i in range(4)]
    assert abs(params['flowing'][0][1] - .2) < 1e-7
    assert params['default'][3][2] == 500
    # material_ocean.default: VLT row 0x58DF8, m_params field 0x58E68;
    # its pointer fixup addresses this three-float4 array in skater.bin.
    assert struct.unpack_from('>HH', database, 0x97330) == (3, 3)
    params['ocean'] = [list(struct.unpack_from('>4f', database, 0x97340 + i * 16))
                       for i in range(3)]
    return dict(image_sha256=hashlib.sha256(image).hexdigest(),
                database_sha256=hashlib.sha256(database).hexdigest(),
                frame_period=period, params=params, pca_frames=frames)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('image', type=Path)
    p.add_argument('skater_bin', type=Path)
    p.add_argument('--header', type=Path, required=True)
    p.add_argument('--report', type=Path, required=True)
    a = p.parse_args()
    result = extract(a.image.read_bytes(), a.skater_bin.read_bytes())
    text = '// Generated by tools/extract_skate2_water.py from original local data.\n'
    text += '// 30 Hz authored PCA animation; rows: mean, R0, R1, G0, G1, B0, B1.\n'
    text += '#pragma once\nnamespace skate3::skate2_water {\n'
    text += 'inline constexpr float kPcaFrames[30][28] = {\n'
    for frame in result['pca_frames']:
        text += '  {' + ', '.join(f'{v:.9e}f' for v in frame) + '},\n'
    text += '};\n}  // namespace skate3::skate2_water\n'
    a.header.write_text(text)
    a.report.write_text(json.dumps(result, indent=2))
    print('Extracted 30 PCA frames and original water/default/flowing/ocean parameters.')


if __name__ == '__main__':
    main()
